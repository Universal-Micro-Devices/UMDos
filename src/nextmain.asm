; ============================================================
; nextmain.asm - 第六级 (LBA 46..49, 0xE000)：64 位跳板
;   FirstMain 已进入长模式并把 bootinfo 放在 0x7000，
;   这里只负责把 bootinfo 交给 C 内核（0x10000）。
; ============================================================
[BITS 64]
[ORG 0xE000]

    mov rdi, 0x7000                 ; bootinfo
    mov rsp, 0x90000
    jmp 0x10000                     ; -> _start (C 内核)

times (4 * 512) - ($ - $$) db 0
